document.addEventListener('DOMContentLoaded', function () {
    fetchMitreData();

    const refreshBtn = document.getElementById('refresh-mitre-btn');
    if (refreshBtn) {
        refreshBtn.addEventListener('click', fetchMitreData);
    }
});

let tacticChart = null;
let currentAlertsMap = {};

function fetchMitreData() {
    // Fetch stats & alerts concurrently from real APIs
    Promise.all([
        fetch('/api/mitre/stats').then(res => res.json()),
        fetch('/api/alerts?limit=100').then(res => res.json())
    ]).then(([statsData, alertsData]) => {
        const stats = (statsData.status === 'success' && statsData.stats) ? statsData.stats : [];
        const alerts = (alertsData.status === 'success' && alertsData.alerts) ? alertsData.alerts : [];

        renderMitreStats(stats, alerts);
        renderMitreMatrix(stats);
        renderTacticChart(stats);
        renderMitreAlertsTable(alerts);
    }).catch(err => {
        console.error('Error fetching MITRE data:', err);
    });
}

function renderMitreStats(stats, alerts) {
    const mitreAlerts = alerts.filter(a => a.mitre_technique_id && a.mitre_technique_id !== 'N/A');

    document.getElementById('mitre-total-count').innerText = mitreAlerts.length;
    document.getElementById('mitre-technique-count').innerText = stats.length;

    const tactics = new Set(stats.map(s => s.mitre_tactic).filter(Boolean));
    document.getElementById('mitre-tactic-count').innerText = tactics.size;

    if (stats.length > 0) {
        const topTactic = stats[0].mitre_tactic || 'None';
        document.getElementById('mitre-top-tactic').innerText = topTactic;
    } else {
        document.getElementById('mitre-top-tactic').innerText = 'None';
    }
}

function renderMitreMatrix(stats) {
    const container = document.getElementById('mitre-matrix-container');
    if (!container) return;

    if (!stats || stats.length === 0) {
        container.innerHTML = `
            <div class="text-center text-muted py-5" id="mitre-empty-state">
                <i class="fas fa-shield-halved fa-3x mb-3 text-secondary opacity-50"></i>
                <h5>No MITRE ATT&CK detections available</h5>
                <p class="small">Real detections generated by the Threat Engine will automatically map here.</p>
            </div>
        `;
        return;
    }

    let html = `
        <table class="table table-dark table-bordered table-hover align-middle mb-0" style="font-size: 0.85rem;">
            <thead class="table-black text-secondary">
                <tr>
                    <th>TACTIC</th>
                    <th>TECHNIQUE ID</th>
                    <th>TECHNIQUE NAME</th>
                    <th>DETECTION TYPE</th>
                    <th>DETECTION COUNT</th>
                    <th>SEVERITY</th>
                    <th>MAPPING STATUS</th>
                </tr>
            </thead>
            <tbody>
    `;

    stats.forEach(item => {
        const sevClass = item.severity === 'CRITICAL' ? 'bg-danger text-white' :
            item.severity === 'HIGH' ? 'bg-warning text-dark' : 'bg-info text-dark';

        html += `
            <tr>
                <td><span class="badge bg-secondary">${item.mitre_tactic || 'N/A'}</span></td>
                <td><code class="fw-bold text-info">${item.mitre_technique_id || 'N/A'}</code></td>
                <td class="fw-semibold">${item.mitre_technique_name || 'N/A'}</td>
                <td><span class="badge bg-dark border border-secondary">${item.detection_type || 'N/A'}</span></td>
                <td><span class="badge bg-primary rounded-pill">${item.detection_count} detections</span></td>
                <td><span class="badge ${sevClass}">${item.severity || 'UNKNOWN'}</span></td>
                <td><span class="badge bg-outline border border-warning text-warning">${item.status || 'Potential / Suspected'}</span></td>
            </tr>
        `;
    });

    html += `</tbody></table>`;
    container.innerHTML = html;
}

function renderTacticChart(stats) {
    const ctx = document.getElementById('mitre-tactic-chart')?.getContext('2d');
    if (!ctx) return;

    if (!stats || stats.length === 0) {
        if (tacticChart) tacticChart.destroy();
        return;
    }

    const tacticCounts = {};
    stats.forEach(s => {
        const tactic = s.mitre_tactic || 'Unknown';
        tacticCounts[tactic] = (tacticCounts[tactic] || 0) + s.detection_count;
    });

    const labels = Object.keys(tacticCounts);
    const data = Object.values(tacticCounts);
    const colors = ['#ff6384', '#36a2eb', '#cc65fe', '#ffce56', '#4bc0c0'];

    if (tacticChart) tacticChart.destroy();

    tacticChart = new Chart(ctx, {
        type: 'doughnut',
        data: {
            labels: labels,
            datasets: [{
                data: data,
                backgroundColor: colors.slice(0, labels.length)
            }]
        },
        options: {
            responsive: true,
            plugins: {
                legend: { position: 'bottom', labels: { color: '#ccc' } }
            }
        }
    });
}

function renderMitreAlertsTable(alerts) {
    const tbody = document.getElementById('mitre-alerts-tbody');
    if (!tbody) return;

    currentAlertsMap = {};
    const mitreAlerts = alerts.filter(a => a.mitre_technique_id && a.mitre_technique_id !== 'N/A');

    if (mitreAlerts.length === 0) {
        tbody.innerHTML = `
            <tr>
                <td colspan="9" class="text-center text-muted py-4">No MITRE ATT&CK detections available</td>
            </tr>
        `;
        return;
    }

    tbody.innerHTML = mitreAlerts.map(a => {
        currentAlertsMap[a.id] = a;
        const sevClass = a.severity === 'CRITICAL' ? 'badge bg-danger' :
            a.severity === 'HIGH' ? 'badge bg-warning text-dark' : 'badge bg-info text-dark';

        return `
            <tr>
                <td class="small text-muted">${a.time_local || 'N/A'}</td>
                <td><code class="fw-bold text-info">${a.mitre_technique_id}</code></td>
                <td class="fw-semibold">${a.mitre_technique_name || 'N/A'}</td>
                <td><span class="badge bg-secondary">${a.mitre_tactic || 'N/A'}</span></td>
                <td><code>${a.detection_type || a.alert_type}</code></td>
                <td><span class="badge bg-dark border border-secondary">${a.source_ip || 'N/A'}</span></td>
                <td><span class="${sevClass}">${a.severity}</span></td>
                <td><span class="badge border border-warning text-warning">${a.mitre_status || 'Potential / Suspected'}</span></td>
                <td>
                    <button class="btn btn-xs btn-outline-info" onclick="inspectAlert(${a.id})">
                        <i class="fas fa-eye me-1"></i>Inspect
                    </button>
                </td>
            </tr>
        `;
    }).join('');
}

function inspectAlert(alertId) {
    const alert = currentAlertsMap[alertId];
    if (!alert) return;

    const modalBody = document.getElementById('alert-detail-body');
    if (!modalBody) return;

    modalBody.innerHTML = `
        <div class="row g-3">
            <div class="col-md-6">
                <div class="p-3 rounded bg-black bg-opacity-50 border border-secondary">
                    <h6 class="text-info border-bottom border-secondary pb-2 mb-3"><i class="fas fa-info-circle me-2"></i>General Overview</h6>
                    <p class="mb-1"><strong>Detection Type:</strong> <code>${alert.detection_type || alert.alert_type}</code></p>
                    <p class="mb-1"><strong>Title:</strong> ${alert.title}</p>
                    <p class="mb-1"><strong>Description:</strong> ${alert.description}</p>
                    <p class="mb-1"><strong>Severity:</strong> <span class="badge bg-warning text-dark">${alert.severity}</span></p>
                    <p class="mb-0"><strong>Timestamp:</strong> ${alert.time_local || alert.timestamp}</p>
                </div>
            </div>

            <div class="col-md-6">
                <div class="p-3 rounded bg-black bg-opacity-50 border border-secondary">
                    <h6 class="text-danger border-bottom border-secondary pb-2 mb-3"><i class="fas fa-crosshairs me-2"></i>MITRE ATT&CK Details</h6>
                    <p class="mb-1"><strong>Technique ID:</strong> <code class="fs-6 text-info">${alert.mitre_technique_id || 'N/A'}</code></p>
                    <p class="mb-1"><strong>Technique Name:</strong> ${alert.mitre_technique_name || 'N/A'}</p>
                    <p class="mb-1"><strong>Tactic:</strong> <span class="badge bg-secondary">${alert.mitre_tactic || 'N/A'}</span></p>
                    <p class="mb-0"><strong>Mapping Confidence:</strong> <span class="badge border border-warning text-warning">${alert.mitre_status || 'Potential / Suspected'}</span></p>
                </div>
            </div>

            <div class="col-md-12">
                <div class="p-3 rounded bg-black bg-opacity-50 border border-secondary">
                    <h6 class="text-warning border-bottom border-secondary pb-2 mb-3"><i class="fas fa-network-wired me-2"></i>Network Telemetry & Evidence</h6>
                    <div class="row g-2 small mb-3">
                        <div class="col-md-3"><strong>Source IP:</strong> <code>${alert.source_ip || 'N/A'}</code></div>
                        <div class="col-md-3"><strong>Destination IP:</strong> <code>${alert.destination_ip || 'N/A'}</code></div>
                        <div class="col-md-3"><strong>Protocol:</strong> <code>${alert.protocol || 'N/A'}</code></div>
                        <div class="col-md-3"><strong>Ports:</strong> <code>${alert.source_port || '*'} -> ${alert.destination_port || '*'}</code></div>
                    </div>
                    <div class="p-2 rounded bg-black text-success font-monospace small">
                        <strong>Evidence:</strong> ${alert.evidence || alert.details || 'No additional evidence recorded.'}
                    </div>
                </div>
            </div>
        </div>
    `;

    const modal = new bootstrap.Modal(document.getElementById('alertDetailModal'));
    modal.show();
}
